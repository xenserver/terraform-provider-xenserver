type vifResourceModel struct {
	Network     types.String `tfsdk:"network_uuid"`
	Device      types.String `tfsdk:"device"`
	VIF         types.String `tfsdk:"vif_ref"`
	MAC         types.String `tfsdk:"mac"`
	OtherConfig types.Map    `tfsdk:"other_config"`
	IPv4Address types.String `tfsdk:"ipv4_address"`
	IPv4Gateway types.String `tfsdk:"ipv4_gateway"`
}

var vifResourceModelAttrTypes = map[string]attr.Type{
	"network_uuid": types.StringType,
	"device":       types.StringType,
	"vif_ref":      types.StringType,
	"mac":          types.StringType,
	"other_config": types.MapType{ElemType: types.StringType},
	"ipv4_address": types.StringType,
	"ipv4_gateway": types.StringType,
}

func vifSchema() map[string]schema.Attribute {
	return map[string]schema.Attribute{
		"network_uuid": schema.StringAttribute{
			MarkdownDescription: "Network UUID to attach to VIF.",
			Required:            true,
		},
		"device": schema.StringAttribute{
			MarkdownDescription: "Order in which VIF backends are created by [XAPI](https://github.com/xapi-project/xen-api), default to be `\"0\"`." + "<br />" +
				"If this value is changed, the VIF will be recreated.",
			Required: true,
			Validators: []validator.String{
				stringvalidator.RegexMatches(
					regexp.MustCompile(`^[0-9]+$`),
					"Input is not a valid device number",
				),
			},
		},
		"vif_ref": schema.StringAttribute{
			Computed: true,
		},
		"mac": schema.StringAttribute{
			MarkdownDescription: "MAC address of the VIF, default to be a random MAC address generated by XenServer." +
				"\n\n-> **Note:** `mac` is not allowed to be updated. Removing it from the configuration later has no effect.",
			Optional: true,
			Computed: true,
			Validators: []validator.String{
				// match MAC address regex
				stringvalidator.RegexMatches(
					regexp.MustCompile(`^([0-9A-Fa-f]{2}[:-]){5}([0-9A-Fa-f]{2})$`),
					"Input is not a valid MAC address",
				),
			},
		},
		"other_config": schema.MapAttribute{
			MarkdownDescription: "The additional configuration of the network interface, default to be `{}`.Find more details in [advanced-settings-for-network-interfaces](https://docs.xenserver.com/en-us/xenserver/developer/sdk-guide/xs-api-extensions#advanced-settings-for-network-interfaces).",
			ElementType:         types.StringType,
			Optional:            true,
			Computed:            true,
		},
		"ipv4_address": schema.StringAttribute{
			MarkdownDescription: "Static IPv4 address for this interface in CIDR notation (address and prefix, e.g. `192.168.10.25/24`). Omit to use DHCP." +
				"\n\n-> **Note:** 1. This is for **Windows guests only** and requires the XenServer Windows guest tools to be pre-installed in the template.<br>" +
				"2. Setting it requires the VM to be running, so the provider starts it to apply the address.<br>" +
				"3. Ensure the `ipv4_address` and `ipv4_gateway` are valid for the interface's network and not already in use, otherwise the guest tools may fail to apply them and the interface stays on DHCP.<br>" +
				"4. The provider only assigns the address. To make it reachable, also ensure the guest's remote-access service is configured.<br>",
			Optional: true,
			Validators: []validator.String{
				stringvalidator.RegexMatches(
					regexp.MustCompile(`^((25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.){3}(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)/([0-9]|[12][0-9]|3[0-2])$`),
					"Input is not a valid IPv4 address in CIDR notation. It needs to be like <address>/<prefix length>, e.g. 192.168.10.25/24",
				),
			},
		},
		"ipv4_gateway": schema.StringAttribute{
			MarkdownDescription: "Default IPv4 gateway for this interface." +
				"\n\n-> **Note:** Only used together with `ipv4_address`.",
			Optional: true,
			Validators: []validator.String{
				stringvalidator.RegexMatches(
					regexp.MustCompile(`^((25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.){3}(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)$`),
					"Input is not a valid IPv4 gateway address, e.g. 192.168.10.1",
				),
				stringvalidator.AlsoRequires(path.MatchRelative().AtParent().AtName("ipv4_address")),
			},
		},
	}
}

func setVIFDefaults(ctx context.Context, vif *vifResourceModel) {
	// Work around for https://github.com/hashicorp/terraform-plugin-framework/issues/726
	if vif.MAC.IsUnknown() {
		vif.MAC = types.StringValue("")
	}

	if vif.OtherConfig.IsUnknown() {
		var diags diag.Diagnostics
		vif.OtherConfig, diags = types.MapValueFrom(ctx, types.StringType, map[string]string{})
		if diags.HasError() {
			tflog.Debug(ctx, "unable to set VIF other config")
		}
	}
}

type vifIPv4Reconfig struct {
	vifRef  xenapi.VIFRef
	device  string
	mode    xenapi.VifIpv4ConfigurationMode
	address string
	gateway string
}

func configureVIFsIPv4(ctx context.Context, session *xenapi.Session, vmRef xenapi.VMRef, plan vmResourceModel, state vmResourceModel) error {
	planVIFs := make([]vifResourceModel, 0, len(plan.NetworkInterface.Elements()))
	diags := plan.NetworkInterface.ElementsAs(ctx, &planVIFs, false)
	if diags.HasError() {
		return errors.New("unable to get Network Interface elements")
	}
	planVIFsMap := make(map[string]vifResourceModel)
	for _, vif := range planVIFs {
		if !vif.IPv4Address.IsNull() && !vif.IPv4Address.IsUnknown() {
			planVIFsMap[vif.Device.ValueString()] = vif
		}
	}

	stateVIFs := make([]vifResourceModel, 0, len(state.NetworkInterface.Elements()))
	if !state.NetworkInterface.IsNull() && !state.NetworkInterface.IsUnknown() {
		diags = state.NetworkInterface.ElementsAs(ctx, &stateVIFs, false)
		if diags.HasError() {
			return errors.New("unable to get Network Interface elements from state")
		}
	}
	stateVIFsMap := make(map[string]vifResourceModel)
	for _, vif := range stateVIFs {
		if !vif.IPv4Address.IsNull() && !vif.IPv4Address.IsUnknown() {
			stateVIFsMap[vif.Device.ValueString()] = vif
		}
	}

	if len(planVIFsMap) == 0 && len(stateVIFsMap) == 0 {
		return nil
	}

	vmVIFs, err := xenapi.VM.GetVIFs(session, vmRef)
	if err != nil {
		return errors.New(err.Error())
	}

	expectStaticIP := make(map[string]string)
	resetStaticIP := make(map[string]string)
	var reconfigs []vifIPv4Reconfig
	for _, vifRef := range vmVIFs {
		record, err := xenapi.VIF.GetRecord(session, vifRef)
		if err != nil {
			return errors.New(err.Error())
		}

		mode, address, gateway := xenapi.VifIpv4ConfigurationModeDHCP, "", ""
		if vif, ok := planVIFsMap[record.Device]; ok {
			address = vif.IPv4Address.ValueString()
			gateway = vif.IPv4Gateway.ValueString()
			if record.Ipv4ConfigurationMode == xenapi.VifIpv4ConfigurationModeStatic &&
				len(record.Ipv4Addresses) > 0 && record.Ipv4Addresses[0] == address &&
				record.Ipv4Gateway == gateway {
				continue
			}
			mode = xenapi.VifIpv4ConfigurationModeStatic
			newIP, _, _ := strings.Cut(address, "/")
			expectStaticIP[record.Device] = newIP
		} else if record.Ipv4ConfigurationMode != xenapi.VifIpv4ConfigurationModeStatic {
			continue
		} else if len(record.Ipv4Addresses) > 0 {
			oldIP, _, _ := strings.Cut(record.Ipv4Addresses[0], "/")
			resetStaticIP[record.Device] = oldIP
		}
		tflog.Debug(ctx, "-----> To configure VIF IPv4: device="+record.Device+" mode="+string(mode)+" address="+address+" gateway="+gateway)
		reconfigs = append(reconfigs, vifIPv4Reconfig{vifRef, record.Device, mode, address, gateway})
	}

	if len(reconfigs) == 0 {
		return nil
	}

	if err := startVM(session, vmRef); err != nil {
		return err
	}

	for _, rc := range reconfigs {
		// The guest tool still takes a while to come up after boot, so the loop below retries
		// while XAPI reports VM_LACKS_FEATURE.
		timeoutChan := time.After(120 * time.Second)
		for {
			err := xenapi.VIF.ConfigureIpv4(session, rc.vifRef, rc.mode, rc.address, rc.gateway)
			if err == nil {
				break
			}
			if !strings.Contains(err.Error(), "VM_LACKS_FEATURE") {
				return errors.New(err.Error())
			}
			select {
			case <-timeoutChan:
				return errors.New("timed out waiting for the guest tools to advertise feature-static-ip-setting on device " + rc.device + "; ensure the Windows guest tools are installed.")
			default:
				tflog.Debug(ctx, "-----> Waiting for guest tools to advertise feature-static-ip-setting")
				time.Sleep(5 * time.Second)
			}
		}
		tflog.Debug(ctx, "-----> ConfigureIpv4 finished for device "+rc.device)
	}

	// ip_addresses/default_ip are only read back when check_ip_timeout > 0
	if plan.CheckIPTimeout.IsUnknown() || plan.CheckIPTimeout.ValueInt64() == 0 {
		return nil
	}

	if err := waitForVIFsIP(ctx, session, vmRef, expectStaticIP, false); err != nil {
		return err
	}
	return waitForVIFsIP(ctx, session, vmRef, resetStaticIP, true)
}

func waitForVIFsIP(ctx context.Context, session *xenapi.Session, vmRef xenapi.VMRef, staticIPs map[string]string, resetToDHCP bool) error {
	if len(staticIPs) == 0 {
		return nil
	}
	timeoutChan := time.After(30 * time.Second)
	for {
		vmRecord, err := xenapi.VM.GetRecord(session, vmRef)
		if err != nil {
			return errors.New(err.Error())
		}
		ipAddresses, _ := getIPAddressesFromMetrics(session, vmRecord)
		pending := false
		for device, staticIP := range staticIPs {
			ip, ok := ipAddresses[device]
			if pending = !ok || (ip == staticIP) == resetToDHCP; pending {
				break
			}
		}
		if !pending {
			return nil
		}
		select {
		case <-timeoutChan:
			if resetToDHCP {
				tflog.Warn(ctx, "timed out waiting for the guest to apply DHCP; ip_addresses/default_ip may be stale")
			} else {
				tflog.Warn(ctx, "timed out waiting for the guest to apply the static IPv4; check it is valid and not in use; ip_addresses/default_ip may still show DHCP")
			}
			return nil
		default:
			tflog.Debug(ctx, "-----> Waiting for guest to apply IP")
			time.Sleep(5 * time.Second)
		}
	}
}

func createVIF(ctx context.Context, vif vifResourceModel, vmRef xenapi.VMRef, session *xenapi.Session) error {
	var vifRef xenapi.VIFRef
	networkRef, err := xenapi.Network.GetByUUID(session, vif.Network.ValueString())
	if err != nil {
		return errors.New(err.Error())
	}

	setVIFDefaults(ctx, &vif)

	otherConfig := make(map[string]string)
	diags := vif.OtherConfig.ElementsAs(ctx, &otherConfig, false)
	if diags.HasError() {
		return errors.New("unable to get VIF other config")
	}

	vifRecord := xenapi.VIFRecord{
		VM:      vmRef,
		Network: networkRef,
		Device:  vif.Device.ValueString(),
		MAC:     vif.MAC.ValueString(),
		// from XAPI code, the mtu is actually works when set in vif.other_config instead of vif.MTU, give it a default value here
		MTU:              1500,
		OtherConfig:      otherConfig,
		LockingMode:      xenapi.VifLockingModeNetworkDefault,
		MACAutogenerated: vif.MAC.ValueString() == "",
	}

	vifRef, err = xenapi.VIF.Create(session, vifRecord)
	if err != nil {
		return errors.New(err.Error())
	}

	vmPowerState, err := xenapi.VM.GetPowerState(session, vmRef)
	if err != nil {
		return errors.New(err.Error())
	}

	if vmPowerState == xenapi.VMPowerStateRunning {
		if err = xenapi.VIF.Plug(session, vifRef); err != nil {
			return errors.New(err.Error())
		}
	}

	return nil
}

func createVIFs(ctx context.Context, session *xenapi.Session, vmRef xenapi.VMRef, data vmResourceModel) error {
	elements := make([]vifResourceModel, 0, len(data.NetworkInterface.Elements()))
	diags := data.NetworkInterface.ElementsAs(ctx, &elements, false)
	if diags.HasError() {
		return errors.New("unable to get Network Interface elements")
	}

	// removed existing VIFs in VM template
	existingVIFs, err := xenapi.VM.GetVIFs(session, vmRef)
	if err != nil {
		return errors.New(err.Error())
	}

	for _, vif := range existingVIFs {
		if err = xenapi.VIF.Destroy(session, vif); err != nil {
			return errors.New(err.Error())
		}
	}

	for _, vif := range elements {
		if err = createVIF(ctx, vif, vmRef, session); err != nil {
			return errors.New(err.Error())
		}
	}
	return nil
}

func vifResourceModelUpdateCheck(plan vifResourceModel, state vifResourceModel) error {
	if plan.MAC.ValueString() != "" && !plan.MAC.Equal(state.MAC) {
		return errors.New(`"network_interface.mac" doesn't expected to be updated`)
	}
	return nil
}

// updateVIF updates the VIFs in the VM based on the plan and state, the logic is similar to updateVBDs
func updateVIFs(ctx context.Context, plan vmResourceModel, state vmResourceModel, vmRef xenapi.VMRef, session *xenapi.Session) error {
	// Get VIFs from plan and state
	planVIFs := make([]vifResourceModel, 0, len(plan.NetworkInterface.Elements()))
	diags := plan.NetworkInterface.ElementsAs(ctx, &planVIFs, false)
	if diags.HasError() {
		return errors.New("unable to get VIFs in plan data")
	}

	stateVIFs := make([]vifResourceModel, 0, len(state.NetworkInterface.Elements()))
	diags = state.NetworkInterface.ElementsAs(ctx, &stateVIFs, false)
	if diags.HasError() {
		return errors.New("unable to get VIFs in state data")
	}

	var err error
	planVIFsMap := make(map[string]vifResourceModel)
	for _, vif := range planVIFs {
		planVIFsMap[vif.Device.String()+vif.Network.String()] = vif
	}

	stateVIFsMap := make(map[string]vifResourceModel)
	for _, vif := range stateVIFs {
		stateVIFsMap[vif.Device.String()+vif.Network.String()] = vif
	}

	vmState, err := xenapi.VM.GetPowerState(session, vmRef)
	if err != nil {
		return errors.New(err.Error())
	}

	// Destroy VIFs that are not in plan, destroy VIFs first to avoid error "DEVICE_ALREADY_EXISTS"
	for networkUUID, stateVIF := range stateVIFsMap {
		if _, ok := planVIFsMap[networkUUID]; !ok {
			vifRef := xenapi.VIFRef(stateVIF.VIF.ValueString())
			if vmState == xenapi.VMPowerStateRunning {
				allowedOps, err := xenapi.VIF.GetAllowedOperations(session, vifRef)
				if err != nil {
					return errors.New(err.Error())
				}
				if slices.Contains(allowedOps, xenapi.VifOperationsUnplug) {
					tflog.Debug(ctx, "---> Unplug VIF when VM is running.")
					err = xenapi.VIF.Unplug(session, vifRef)
					if err != nil {
						return errors.New(err.Error())
					}
				}
			}
			tflog.Debug(ctx, "---> Destroy VIF:	"+stateVIF.VIF.String())
			err = xenapi.VIF.Destroy(session, vifRef)
			if err != nil {
				if !strings.Contains(err.Error(), "HANDLE_INVALID") {
					return errors.New(err.Error())
				}
				tflog.Debug(ctx, "HANDLE_INVALID: VIF already been destroyed.")
			}
		}
	}

	// Create VIFs that are in plan but not in state, Update VIFs if already exists and attributes changed
	for deviceNetwork, planVIF := range planVIFsMap {
		stateVIF, ok := stateVIFsMap[deviceNetwork]
		if !ok {
			tflog.Debug(ctx, "---> Create VIF with Network: "+planVIF.Network.String()+" <---")
			err = createVIF(ctx, planVIF, vmRef, session)
			if err != nil {
				return err
			}
		} else {
			setVIFDefaults(ctx, &planVIF)

			tflog.Debug(ctx, "---> Update VIF "+stateVIF.VIF.String()+" <---")
			err := vifResourceModelUpdateCheck(planVIF, stateVIF)
			if err != nil {
				return err
			}

			if !planVIF.OtherConfig.Equal(stateVIF.OtherConfig) {
				otherConfig := make(map[string]string)
				diags := planVIF.OtherConfig.ElementsAs(ctx, &otherConfig, false)
				if diags.HasError() {
					return errors.New("unable to get network_interface.other_config")
				}

				err = xenapi.VIF.SetOtherConfig(session, xenapi.VIFRef(stateVIF.VIF.ValueString()), otherConfig)
				if err != nil {
					return errors.New(err.Error())
				}
			}
		}
	}

	return nil
}
